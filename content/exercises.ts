/** Parses the library; throws with the exercise id on the first invalid entry. */
export function loadExerciseLibrary(inputs: ExerciseInput[] = exerciseInputs): Record<string, Exercise> {
  const out: Record<string, Exercise> = {};
  for (const e of inputs) {
    const r = exerciseSchema.safeParse(e);
    if (!r.success) {
      const lines = r.error.issues.map((i) => `  • ${i.path.join('.')}: ${i.message}`).join('\n');
      throw new Error(`Exercise "${e.id}" is invalid:\n${lines}`);
    }
    if (out[r.data.id]) throw new Error(`Duplicate exercise id "${r.data.id}"`);
    out[r.data.id] = r.data;
  }
  for (const e of Object.values(out)) {
    for (const alt of e.alternatives) {
      if (!out[alt]) throw new Error(`Exercise "${e.id}" lists unknown alternative "${alt}"`);
    }
  }
  return out;
}
